-- Every social decision is coupled to the authorized gallery moderation action.
-- Selecting one approved photo per post avoids accidental bulk publication.
create or replace function memories_private.queue_social_after_approval()
returns trigger language plpgsql security definer set search_path = '' as $$
declare chosen uuid;
begin
  if NEW.status = 'approved' and NEW.gallery_consent and NEW.social_consent
    and NEW.social_reviewed and not NEW.privacy_hold then
    select p.id into chosen from public.memory_photos p
      where p.post_id=NEW.id order by p.position asc limit 1;
    if chosen is not null then
      insert into public.memory_social_outbox(post_id,photo_id,platform,publication_key)
      select NEW.id,chosen,c.platform,NEW.id::text||':'||chosen::text||':'||c.platform||':v1'
      from public.memory_social_channels c
      on conflict(photo_id,platform) do nothing;
    end if;
  else
    update public.memory_social_outbox set status='cancelled',last_error='Consent or approval withdrawn'
      where post_id=NEW.id and status in ('ready','failed');
    update public.memory_social_outbox set removal_required=true,
        last_error='Publication may require external removal'
      where post_id=NEW.id and status in ('dispatching','accepted','published');
  end if;
  return NEW;
end;
$$;
drop trigger if exists memory_social_on_post_change on public.memory_posts;
create trigger memory_social_on_post_change after update of status,social_consent,social_reviewed,privacy_hold on public.memory_posts
for each row execute function memories_private.queue_social_after_approval();
revoke all on function memories_private.queue_social_after_approval() from public, anon, authenticated;

-- A one-shot, atomic dispatch claim. Never automatically retry uncertain webhook
-- deliveries: Zapier receiving a request does NOT prove Facebook/Instagram published.
create or replace function public.memory_claim_social_outbox(p_platform text)
returns setof public.memory_social_outbox language plpgsql security definer set search_path = '' as $$
declare chosen bigint; weekly_limit integer;
begin
  select max_per_seven_days into weekly_limit from public.memory_social_channels
    where platform=p_platform and enabled=true;
  if weekly_limit is null or weekly_limit < 1 then return; end if;
  if (select count(*) from public.memory_social_outbox
      where platform=p_platform and status in ('dispatching','accepted','published')
        and coalesce(attempted_at,published_at) >= now()-interval '7 days') >= weekly_limit then return; end if;
  select o.id into chosen from public.memory_social_outbox o
    join public.memory_posts m on m.id=o.post_id
    join public.memory_photos p on p.id=o.photo_id
    where o.platform=p_platform and o.status='ready' and o.scheduled_at<=now()
      and m.status='approved' and m.gallery_consent and m.social_consent
      and m.social_reviewed and not m.privacy_hold
      and not exists(
        select 1 from public.memory_social_outbox earlier
        join public.memory_posts em on em.id=earlier.post_id
        where earlier.platform=p_platform and earlier.status='published'
          and earlier.published_at >= now()-interval '5 days' and em.team_id=m.team_id
      )
    order by o.scheduled_at,o.id
    for update of o skip locked limit 1;
  if chosen is null then return; end if;
  return query update public.memory_social_outbox
    set status='dispatching',attempts=attempts+1,attempted_at=now(),last_error=null
    where id=chosen and status='ready' returning *;
end;
$$;
revoke all on function public.memory_claim_social_outbox(text) from public, anon, authenticated;
grant execute on function public.memory_claim_social_outbox(text) to service_role;

