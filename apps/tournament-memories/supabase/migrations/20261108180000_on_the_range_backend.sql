create or replace function memories_private.can_moderate(target_team text)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(
    select 1 from public.memory_moderators m
    where m.user_id = (select auth.uid())
      and (m.team_id is null or m.team_id = target_team)
  );
$$;
revoke all on function memories_private.can_moderate(text) from public;
grant execute on function memories_private.can_moderate(text) to anon,authenticated;

