-- Returns false on over-limit. Called only by the server-side Edge Function.
create or replace function public.memory_consume_quota(
  p_hash text,p_action text,p_limit integer,p_minutes integer)
returns boolean language plpgsql security definer set search_path = '' as $$
declare n integer; bucket timestamptz;
begin
  if length(p_hash) <> 64 or p_action not in ('begin','comment','react')
    or p_limit not between 1 and 100000 or p_minutes not between 1 and 1440 then return false; end if;
  bucket := to_timestamp(floor(extract(epoch from now()) / (p_minutes*60)) * (p_minutes*60));
  insert into public.memory_abuse_counters(subject_hash,action,window_start,hits)
    values(p_hash,p_action,bucket,1)
  on conflict(subject_hash,action,window_start)
    do update set hits = public.memory_abuse_counters.hits + 1
  returning hits into n;
  return n <= p_limit;
end;
$$;
revoke all on function public.memory_consume_quota(text,text,integer,integer) from public, anon, authenticated;
grant execute on function public.memory_consume_quota(text,text,integer,integer) to service_role;

